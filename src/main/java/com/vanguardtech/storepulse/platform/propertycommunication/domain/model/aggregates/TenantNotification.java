package com.vanguardtech.storepulse.platform.propertycommunication.domain.model.aggregates;

import com.vanguardtech.storepulse.platform.propertycommunication.domain.exceptions.PropertyCommunicationError;
import com.vanguardtech.storepulse.platform.propertycommunication.domain.model.events.TenantNotifiedEvent;
import com.vanguardtech.storepulse.platform.propertycommunication.domain.model.valueobjects.NotificationChannel;
import com.vanguardtech.storepulse.platform.propertycommunication.domain.model.valueobjects.NotificationStatus;
import com.vanguardtech.storepulse.platform.propertycommunication.domain.model.valueobjects.NotificationType;
import com.vanguardtech.storepulse.platform.shared.domain.exceptions.BusinessRuleException;
import com.vanguardtech.storepulse.platform.shared.domain.model.aggregates.AuditableAbstractAggregateRoot;
import jakarta.persistence.*;
import lombok.Getter;
import java.time.Instant;

/**
 * Notification sent to a tenant (Aggregate Root), either published by the administrator or
 * generated by an event such as {@code UtilityBillIssued}. It starts pending and ends sent or failed.
 */
@Entity
@Table(name = "tenant_notifications")
@Getter
public class TenantNotification extends AuditableAbstractAggregateRoot<TenantNotification> {

    public static final int TITLE_MAX_LENGTH = 120;
    public static final int BODY_MAX_LENGTH = 1000;

    @Column(nullable = false)
    private Long tenantId;

    private Long commercialUnitId;

    @Column(nullable = false)
    private Long galleryAdministratorId;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private NotificationType type;

    @Column(nullable = false, length = TITLE_MAX_LENGTH)
    private String title;

    @Column(nullable = false, length = BODY_MAX_LENGTH)
    private String body;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private NotificationChannel channel;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private NotificationStatus status;

    /** Whether the tenant already opened it. */
    @Column(name = "is_read", nullable = false)
    private boolean read;

    /** Resource that originated it, such as a conversation or a bill. */
    private Long referenceId;

    protected TenantNotification() {
    }

    public TenantNotification(Long tenantId, Long commercialUnitId, Long galleryAdministratorId, NotificationType type,
                              String title, String body, NotificationChannel channel, Long referenceId) {
        if (tenantId == null || tenantId <= 0)
            throw new IllegalArgumentException("Tenant id must be a positive number");
        if (galleryAdministratorId == null || galleryAdministratorId <= 0)
            throw new IllegalArgumentException("Gallery administrator id must be a positive number");
        if (type == null || channel == null)
            throw new IllegalArgumentException("Notification type and channel are required");
        if (title == null || title.isBlank() || title.trim().length() > TITLE_MAX_LENGTH)
            throw new BusinessRuleException(PropertyCommunicationError.INVALID_NOTIFICATION_TITLE);
        if (body == null || body.isBlank() || body.trim().length() > BODY_MAX_LENGTH)
            throw new BusinessRuleException(PropertyCommunicationError.INVALID_NOTIFICATION_BODY);
        this.tenantId = tenantId;
        this.commercialUnitId = commercialUnitId;
        this.galleryAdministratorId = galleryAdministratorId;
        this.type = type;
        this.title = title.trim();
        this.body = body.trim();
        this.channel = channel;
        this.status = NotificationStatus.PENDING;
        this.read = false;
        this.referenceId = referenceId;
    }

    public boolean isFailed() {
        return status == NotificationStatus.FAILED;
    }

    /** Delivery confirmed. */
    public void markSent() {
        this.status = NotificationStatus.SENT;
        registerEvent(new TenantNotifiedEvent(getId(), tenantId, type.name(), Instant.now()));
    }

    public void markFailed() {
        this.status = NotificationStatus.FAILED;
    }

    /** A failed notification goes back to pending to be delivered again. */
    public void retry() {
        if (!isFailed())
            throw new BusinessRuleException(PropertyCommunicationError.NOTIFICATION_NOT_FAILED);
        this.status = NotificationStatus.PENDING;
    }

    public void markRead() {
        this.read = true;
    }
}
